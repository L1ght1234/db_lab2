DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;

CREATE TABLE sports (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(30)  NOT NULL UNIQUE,
    name varchar(100) NOT NULL
);

CREATE TABLE venues (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     varchar(150) NOT NULL,
    city     varchar(100) NOT NULL,
    capacity integer      NOT NULL CHECK (capacity > 0)
);

CREATE TABLE tournaments (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_id integer      NOT NULL REFERENCES sports(id) ON DELETE RESTRICT,
    name     varchar(150) NOT NULL,
    season   varchar(20)  NOT NULL
);

CREATE TABLE teams (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_id integer      NOT NULL REFERENCES sports(id) ON DELETE RESTRICT,
    name     varchar(120) NOT NULL,
    city     varchar(100) NOT NULL
);

CREATE TABLE players (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id          integer      NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    full_name        varchar(150) NOT NULL,
    birth_year       integer      NOT NULL,
    default_position varchar(50)  NOT NULL
);

CREATE TABLE matches (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id integer      NOT NULL REFERENCES tournaments(id) ON DELETE RESTRICT,
    sport_id      integer      NOT NULL REFERENCES sports(id) ON DELETE RESTRICT,
    venue_id      integer      NOT NULL REFERENCES venues(id) ON DELETE RESTRICT,
    home_team_id  integer      NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    away_team_id  integer      NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    stage_name    varchar(100) NOT NULL,
    scheduled_at  timestamptz  NOT NULL,
    status        varchar(30)  NOT NULL,
    attendance    integer      NOT NULL DEFAULT 0 CHECK (attendance >= 0),
    CONSTRAINT chk_diff_teams CHECK (home_team_id <> away_team_id)
);

CREATE TABLE match_results (
    match_id       integer PRIMARY KEY REFERENCES matches(id) ON DELETE CASCADE,
    home_score     integer NOT NULL CHECK (home_score >= 0),
    away_score     integer NOT NULL CHECK (away_score >= 0),
    winner_team_id integer REFERENCES teams(id) ON DELETE RESTRICT,
    is_extra_time  boolean NOT NULL DEFAULT false,
    is_penalties   boolean NOT NULL DEFAULT false
);

CREATE TABLE match_periods (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id      integer     NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    period_number integer     NOT NULL CHECK (period_number > 0),
    period_label  varchar(40) NOT NULL,
    home_score    integer     NOT NULL CHECK (home_score >= 0),
    away_score    integer     NOT NULL CHECK (away_score >= 0),
    CONSTRAINT uq_match_period UNIQUE (match_id, period_number)
);

CREATE TABLE match_period_stats (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_id  integer       NOT NULL REFERENCES match_periods(id) ON DELETE CASCADE,
    team_id    integer       NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    stat_key   varchar(50)   NOT NULL,
    stat_value numeric(10,2) NOT NULL
);

CREATE TABLE match_lineups (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id            integer       NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    team_id             integer       NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    player_id           integer       NOT NULL REFERENCES players(id) ON DELETE RESTRICT,
    is_starter          boolean       NOT NULL,
    shirt_number        integer       NOT NULL,
    role                varchar(40)   NOT NULL,
    minutes_played      integer       NOT NULL CHECK (minutes_played >= 0),
    rating              numeric(4,2)  NOT NULL,
    primary_stat_name   varchar(40)   NOT NULL,
    primary_stat_val    numeric(10,2) NOT NULL,
    secondary_stat_name varchar(40)   NOT NULL,
    secondary_stat_val  numeric(10,2) NOT NULL
);

CREATE TABLE match_events (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id         integer       NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    team_id          integer       NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    player_id        integer       NOT NULL REFERENCES players(id) ON DELETE RESTRICT,
    assist_player_id integer       REFERENCES players(id) ON DELETE SET NULL,
    period_number    integer       NOT NULL,
    minute           integer       NOT NULL CHECK (minute >= 0),
    event_type       varchar(40)   NOT NULL,
    description      varchar(200)  NOT NULL,
    metric_name      varchar(40),
    metric_val       numeric(10,2)
);
